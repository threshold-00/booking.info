// Reads real pixel dimensions straight from each JPEG's SOF marker, no
// dependency needed. Fixes B3: width/height attrs were hardcoded (1200x900)
// and didn't match the real files, which can cause layout shift.
const dimCache = new Map();
function jpegSize(file) {
  if (dimCache.has(file)) return dimCache.get(file);
  const buf = readFileSync(path.join(ROOT, 'assets/salty-cowboy', file));
  let i = 2, size = null;
  while (i < buf.length - 9) {
    if (buf[i] !== 0xff) { i++; continue; }
    const marker = buf[i + 1];
    if (marker >= 0xc0 && marker <= 0xcf && marker !== 0xc4 && marker !== 0xc8 && marker !== 0xcc) {
      size = { height: buf.readUInt16BE(i + 5), width: buf.readUInt16BE(i + 7) };
      break;
    }
    const len = buf.readUInt16BE(i + 2);
    i += 2 + len;
  }
  dimCache.set(file, size);
  return size;
}

function esc(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}
function fmtIDR(n) {
  return 'IDR ' + n.toLocaleString('en-US');
}
function lowPrice(a) { return Math.min(...a.durations.map(d => d.priceIDR)); }
function highPriceAll() { return Math.max(...activities.map(a => Math.max(...a.durations.map(d => d.priceIDR)))); }
function lowPriceAll() { return Math.min(...activities.map(a => lowPrice(a))); }

function moreFrom(current, n) {
  const sameType = activities.filter(a => a.slug !== current.slug && a.type === current.type);
  const rest = activities.filter(a => a.slug !== current.slug && a.type !== current.type);
  return [...sameType, ...rest].slice(0, n);
}

