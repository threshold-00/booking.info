function jsonLd(a, canonicalPath) {
  const offers = a.durations.map(d => ({
    '@type': 'Offer',
    name: d.label,
    price: String(d.priceIDR),
    priceCurrency: 'IDR',
    url: `https://book.saltycowboybali.com/${a.slug}?ref=threshold`
  }));
  const graph = [
    {
      '@type': 'BreadcrumbList',
      itemListElement: [
        { '@type': 'ListItem', position: 1, name: 'Threshold', item: 'https://thresholdbooking.com/' },
        { '@type': 'ListItem', position: 2, name: 'Bali', item: 'https://thresholdbooking.com/?region=bali#browse' },
        { '@type': 'ListItem', position: 3, name: 'Salty Cowboy', item: 'https://thresholdbooking.com/bali/salty-cowboy/' },
        { '@type': 'ListItem', position: 4, name: a.title, item: `https://thresholdbooking.com${canonicalPath}` }
      ]
    },
    {
      '@type': 'TouristTrip',
      name: a.title,
      description: a.overview,
      image: a.images.map(img => `https://thresholdbooking.com/assets/salty-cowboy/${img.file}`),
      provider: { '@type': 'LocalBusiness', name: 'Salty Cowboy' },
      offers
    },
    {
      '@type': 'FAQPage',
      mainEntity: faqItems(a).map(f => ({
        '@type': 'Question',
        name: f.q,
        acceptedAnswer: { '@type': 'Answer', text: f.a }
      }))
    }
  ];
  return JSON.stringify({ '@context': 'https://schema.org', '@graph': graph }, null, 2);
}

